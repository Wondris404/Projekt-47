def main():
    ids = {row["id"] for row in json.loads((ROOT / "data" / "commodities.json").read_text(encoding="utf-8"))}
    if ids != PATTERNS.keys():
        raise ValueError(f"Commodity coverage mismatch: {ids ^ PATTERNS.keys()}")
    DEST.mkdir(parents=True, exist_ok=True)
    for index, cid in enumerate(sorted(ids)):
        dest = DEST / f"{cid}.png"
        if dest.exists():
            continue
        img = Image.new("RGBA", (32, 32))
        draw = ImageDraw.Draw(img)
        bg = [(54, 81, 112), (112, 76, 53), (69, 105, 76), (103, 75, 106)][index % 4]
        draw.rounded_rectangle((1, 1, 30, 30), radius=5, fill=(28, 31, 37), outline=(11, 14, 18), width=1)
        draw.rounded_rectangle((3, 3, 28, 27), radius=4, fill=bg)
        draw.rectangle((4, 27, 27, 28), fill=(232, 176, 68))
        for y, row in enumerate(PATTERNS[cid]):
            for x, pixel in enumerate(row):
                if pixel == "#":
                    draw.rectangle((8 + x * 2, 7 + y * 2, 9 + x * 2, 8 + y * 2), fill=(239, 238, 222))
        img.save(dest)

if __name__ == "__main__":
    main()
