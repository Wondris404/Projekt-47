def hexc(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def make(name, base_hex, accent_hex, art):
    tpl = Image.open(TEMPLATE).convert("RGBA")
    base = hexc(base_hex)
    acc = hexc(accent_hex)
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    for y in range(32):
        for x in range(32):
            p = tpl.getpixel((x, y))
            if p in (OUTLINE, SHADOW, HILITE) or p[3] == 0:
                im.putpixel((x, y), p)
                continue
            f = 1.0 - 0.28 * max(0, y - 2) / 27.0
            im.putpixel((x, y), (int(base[0] * f), int(base[1] * f), int(base[2] * f), 255))
    inside = lambda x, y: im.getpixel((x, y)) not in (OUTLINE, SHADOW, HILITE) and im.getpixel((x, y))[3] == 255
    ox, oy = 6, 7
    pts = [(ox + i, oy + j) for j, row in enumerate(art) for i, ch in enumerate(row) if ch == "#"]
    for (x, y) in pts:  # tien glyfu (vpravo dole), ako v povodnych ikonach
        for dx, dy in ((1, 0), (0, 1), (1, 1)):
            q = (x + dx, y + dy)
            if q not in pts and 0 <= q[0] < 32 and 0 <= q[1] < 32 and inside(*q):
                c = im.getpixel(q)
                im.putpixel(q, (int(c[0] * 0.45), int(c[1] * 0.45), int(c[2] * 0.45), 255))
    for (x, y) in pts:
        if inside(x, y) or im.getpixel((x, y))[3] == 255:
            im.putpixel((x, y), WHITE)
    for x in range(5, 27):  # farebny pruh dole
        if inside(x, 27):
            im.putpixel((x, 27), acc + (255,))
        if inside(x + 1, 28):
            im.putpixel((x + 1, 28), (int(acc[0] * 0.36), int(acc[1] * 0.36), int(acc[2] * 0.36), 255))
    out = os.path.join(ICONS, name + ".png")
    if os.path.exists(out):
        print("preskakujem existujuci", out)
        return
    im.save(out)
    print("ulozene", out)

if __name__ == "__main__":
    for n, (b, a, art) in GLYPHS.items():
        make(n, b, a, art)
